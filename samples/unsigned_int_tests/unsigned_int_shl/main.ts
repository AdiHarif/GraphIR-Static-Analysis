// All combinations with << between (42, -1, 1.5)
42 << 42;     // uint << uint
42 << -1;     // uint << int
42 << 1.5;    // uint << num
-1 << 42;     // int << uint
-1 << -1;     // int << int
-1 << 1.5;    // int << num
1.5 << 42;    // num << uint
1.5 << -1;    // num << int
1.5 << 1.5;   // num << num
